function badgeSvg(name) {
  const spec = BADGES[name];
  if (!spec) throw new Error(`Unknown Habitat badge: ${name}`);
  const [tile, ink, glyph] = spec;
  return "<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 64 64'>"
    + `<path fill='#${tile}' d='M12 4h28l20 20v28a8 8 0 0 1-8 8H12a8 8 0 0 1-8-8V12a8 8 0 0 1 8-8z'/>`
    + `<g transform='translate(14 16) scale(1.5)' fill='none' stroke='#${ink}' stroke-width='2' `
    + `stroke-linecap='round' stroke-linejoin='round'><path d='${glyph}'/></g></svg>`;
}

function encode(markup) {
  return 'url("data:image/svg+xml,' + markup.replace(/</g, '%3C').replace(/>/g, '%3E').replace(/#/g, '%23') + '")';
}

// Icons a theme paints by hand, outside the Haven Glyphs classes: the signal
// bars on the voice bar. They get a variable even though no glyph class uses them.
const EXTRA = ['signal'];

function svg(name) {
  const spec = ICONS[name];
  if (!spec) throw new Error(`Unknown Habitat icon: ${name}`);
  const [main, heavy] = Array.isArray(spec) ? spec : [spec];
  const extra = heavy ? `<path d='${heavy}' stroke-width='2.8' stroke-linecap='butt'/>` : '';
  return "<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 24 24' fill='none' stroke='black' "
    + "stroke-width='1.75' stroke-linecap='round' stroke-linejoin='round'>"
    + `<path d='${main}'/>${extra}</svg>`;
}

function dataUri(name) {
  return encode(svg(name));
}

function block() {
  const used = [...new Set([...Object.values(GLYPHS), ...EXTRA])].sort();
  const lines = [START, ':root {'];
  for (const name of used) lines.push(`  --hb-icon-${name}: ${dataUri(name)};`);
  lines.push('}');
  const classes = Object.keys(GLYPHS).map((cls) => `.haven-glyph.${cls}::before`);
  lines.push(classes.join(',\n') + ' {');
  lines.push('  content: "";');
  lines.push('  display: inline-block;');
  lines.push('  width: 1.15em;');
  lines.push('  height: 1.15em;');
  lines.push('  vertical-align: -0.2em;');
  lines.push('  background: currentColor;');
  lines.push('  -webkit-mask: var(--hb-icon) center / contain no-repeat;');
  lines.push('  mask: var(--hb-icon) center / contain no-repeat;');
  lines.push('}');
  for (const [cls, name] of Object.entries(GLYPHS)) {
    lines.push(`.haven-glyph.${cls}::before { --hb-icon: var(--hb-icon-${name}); }`);
  }
  lines.push(':root {');
  for (const name of Object.keys(BADGES)) lines.push(`  --hb-badge-${name}: ${encode(badgeSvg(name))};`);
  lines.push('}');
  for (const name of Object.keys(BADGES)) {
    lines.push(`img.badge-icon[src$="/img/badges/${name}.svg"] { content: var(--hb-badge-${name}); }`);
  }
  FACES.forEach((face, digit) => {
    lines.push(`:where([data-user-id$="${digit}"], [data-habitat-avatar-id$="${digit}"]) { --hb-face: ${encode(faceSvg(face))}; }`);
    lines.push(`:where([data-user-id^="${digit}"], [data-habitat-avatar-id^="${digit}"]) { --hb-face-bg: ${FACE_COLORS[digit]}; }`);
  });
  lines.push(END);
  return lines.join('\n');
}

function rewrite(file) {
  const full = path.join(__dirname, '..', 'themes', file);
  const css = fs.readFileSync(full, 'utf8');
  const from = css.indexOf(START);
  const to = css.indexOf(END);
  if (from === -1 || to === -1 || to < from) {
    throw new Error(`${file} has no HABITAT-ICONS markers`);
  }
  fs.writeFileSync(full, css.slice(0, from) + block() + css.slice(to + END.length));
}

if (require.main === module) {
  for (const file of THEMES) rewrite(file);
  console.log(`Habitat icons written to ${THEMES.join(', ')}`);
}

